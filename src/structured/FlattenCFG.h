// ============================================================================
// structured/FlattenCFG.h —— 结构化 IR → 平面 CFG（S06 交付物 #5）
//
// 契约：`docs/handoff/03-设计/结构化IR设计.md` §4.2 与
//       `docs/handoff/03-设计/平面IR与dump格式.md` §6。
//
// ── 三条不可违反的性质 ────────────────────────────────────────────────────
//   ① **纯机械**：只做"展开"，不做任何优化、不做任何判断（§4.2）。
//      一个 `IfOp` → 一个条件块 + 两个分支块 + 一个汇合块，没有例外。
//   ② **唯一边界、单向不回头**：展平之后永远不再回到结构化层（§4.2）。
//   ③ **不改语义**：本关最强的判据是"两种形状跑出同一结果"（轨 E）。
//
// ── ★★ φ 的放置判据（先写进注释再写代码 —— prompt §二.2 的明文要求）★★ ──
//
//   我们**不做** SSA 构造算法（Braun 等，prompt §十.4）：结构化 IR 的形状让
//   φ 的位置**可以直接算出来**。判据（三条）：
//
//   **判据 1（只在汇合点放）**：φ 只出现在**前驱数 ≥ 2** 的块 ——
//     `IfOp` 的汇合块、`WhileOp`/`ForOp` 的循环头、循环出口块。
//     单前驱的块**一个 φ 都不放**（那只是"继续往前走"）。
//
//   **判据 2（只对"在分支里被写、又在汇合后被读"的变量放）**：
//     变量 = 一个 `alloca` 的结果（平面层变量仍在内存里，铁律 1）；
//     "被写" = 该 alloca 在某个分支里有 `store`；
//     "被读" = 该 alloca 在汇合点之后（含循环条件与循环出口之后）有 `load`。
//     ⇒ 一个变量在分支里**只写不读**时**不许多放 φ**（prompt §三.4 第 6 条），
//       实现上表现为：**只有"被读过"的槽才进环境**（死变量的分支不会造 φ）。
//
//   **判据 3（每个 φ 至少有一个非自身入值）**：循环头的每个 φ 至少有一条
//     入边来自循环**外**（循环前的初值）⇒ 这条自动成立；实现上表现为
//     "入值来自循环前环境"而不是"指向 φ 自己"。
//
//   实现方式（"变量版本"法，**不建支配树**）：展平时维护一张
//   `槽(alloca 结果) → 当前值` 的环境映射（`Env`）：
//     * `load` 时先查环境：**命中就用环境里的值**（该变量此刻的值已知）；
//     * `store` 时更新环境（只对"被读过"的槽）；
//     * 汇合时比较各入边上的值：**全部相同 ⇒ 不放 φ**（判据 2 的"不多放"）；
//       不同 ⇒ 在汇合块开头放 `phi <ty> [(%v1 L1) (%v2 L2) …]`，
//       按**前驱块号升序**；某条入边上没有该槽 ⇒ 用该类型的**零常量**补
//       （结构化层的未初始化读是 UB；补零而不是补空，是为了永不产出
//        "操作数为空"的坏 IR）。
//
//   **环境正确性（为什么不需要在展平中途算支配树）**：环境只在**块内**演进，
//   块与块之间通过"显式传入的快照"传递，而快照的构造是**结构化形状**驱动的
//   （分支各拿父环境的副本；汇合点比较入边快照：值相同才继承，不同就发 φ）。
//   ⇒ 环境中出现的每个值，要么定义在**所有**入边都会经过的地方（支配），
//     要么就是刚刚在汇合块里发的 φ。展平**结束**后会算一次支配树，但那是给
//     `FlatVerifier` 与单元断言用的**独立复核**（两条路互相验证：
//     `unit/test_flat.cpp` 有一条断言专门对"人工构造的 CFG"跑支配检查）。
//
//   ⭐ **这不是 mem2reg**（铁律 1 / prompt §十.1）：
//     ① 只有**控制流汇合处必须选择的值**被提升成 φ；
//     ② `alloca` **一个都不删**（不变量 2 仍成立，后端照旧一次性布局栈帧）；
//     ③ 其余变量一律保留 `load`/`store` —— S09 的 mem2reg 仍有大量事可做；
//     ④ 被判据 2 排除的槽（只写不读 / 单入边 / 无汇合）**一个 φ 都不放**
//        （`unit/test_flat.cpp` 有断言钉死这一条）。
//
// ── ★★ 临界边（critical edge）必须拆（prompt §二.3）★★ ──────────────────
//   **临界边** = 一条边的**源块有多个后继**、且**目标块有多个前驱**。
//   危害是**语义性**的：φ 的入值要按"从哪条边来"取值，而临界边上
//   "源块的哪一条边"与"目标块的哪一个前驱"不再是**一一对应** ——
//   φ 无法表达"我这次是从哪条边来的"。
//   ⇒ 展平结束后**扫描全部有向边**，凡 `outdeg(src) > 1 && indeg(dst) > 1`
//     就插入一个**空的中转块**（只有 `br label %dst`），并把 φ 的入值键
//     从 `src` 改到中转块。
//   ⚠️ 这是"能跑通但结果偶尔错"的经典来源（prompt §二.3），轨 E 会抓它。
//
// ── 深度：显式帧栈（prompt §八）──────────────────────────────────────────
//   结构化 IR 的**嵌套**深度由 Parser 的 `kMaxDepth` 限过（4000），但那仍然
//   超过默认栈能安全承受的递归深度（S02 的 `destroyTree` 实测爆过）。
//   ⇒ 展平用**显式帧栈**，不用递归（帧里放"Region 走到第几条 + 续点"）。
//
// 【冻结】`ir/` 的全部类接口 S06 后只增不改；本文件是**唯一**的层边界
//          （D18），同样只增不改。
// ============================================================================
#ifndef SYSY_STRUCTURED_FLATTENCFG_H
#define SYSY_STRUCTURED_FLATTENCFG_H

#include "ir/Module.h"
#include "structured/StructuredIR.h"
#include "support/Diagnostic.h"

namespace sysy {
namespace flat {

// 【前置】`smod == nullptr` 或 `smod->kind == sir::OpKind::Module`；且已跑过
//         `normalizeLoops` + `hoistAllocas`（`alloca` 全在入口 Region）。
// 【后置】把结构化模块展平进 `out`（**由调用方持有**），返回 `&out`；
//         与结构化层**共用同一份类型池**（`ir/Type.h`）。
//         * 全局变量按 `GlobalVarOp` 的顺序与初始化器建好；
//         * 每个函数一个入口块（形参在开头、`alloca` 紧随其后、相对顺序不变）；
//         * φ 按文件头的判据放置；临界边已拆；每块恰好一个终结符；
//         * 结束时调 `rebuildCFG()` + `rebuildUseDef()`。
// 【副作用】只写 `out`；结构化层**一个字节都不改**（展平是"读旧写新"）。
// 【幂等】对同一 `smod` 反复调用，产出逐字节相同的平面 IR。
// 【失败】`smod == nullptr` → 返回 nullptr。任何"超限就放弃"的分支都
//         **先报 error**（prompt §八：不许静默放弃），并把诊断写进 `diags`。
Module* flattenModule(const sir::Op* smod, Module& out, DiagnosticEngine& diags);

}  // namespace flat
}  // namespace sysy
#endif  // SYSY_STRUCTURED_FLATTENCFG_H
